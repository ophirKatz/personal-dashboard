import { writeFileSync } from 'node:fs'

// Regenerates src/features/runescape/archaeology-data.ts from the "Methods" section of
// https://runescape.wiki/w/Archaeology_training. Every excavation hotspot there has an
// "Artefacts from <hotspot>" table; its "Needed" column is how many of each artefact are
// required, which is what the Archaeology collections page tracks against.
//
//   node scripts/generate-archaeology-data.mjs

const UA = 'personal-dashboard (rs3 tracker)' // same as api/runescape.ts; the wiki rejects generic user agents
const METHODS_SECTION = 5 // index of "Methods" in action=parse&prop=sections
const API_URL =
  'https://runescape.wiki/api.php?action=parse&page=Archaeology_training&prop=text&format=json&formatversion=2&redirects=1' +
  `&section=${METHODS_SECTION}`
const OUT = new URL('../src/features/runescape/archaeology-data.ts', import.meta.url)

const dash = s => s.trim().replace(/\s*[-–—]\s*/g, '–') // the wiki mixes hyphens, en dashes and em dashes
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')
const quote = s => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

const res = await fetch(API_URL,{ headers: { 'User-Agent': UA, Accept: 'application/json' } })
if (!res.ok) throw new Error(`Wiki responded ${res.status}`)
const { parse } = await res.json()
if (!parse?.text) throw new Error('Wiki returned no page text')

// Imported after the fetch: jsdom swaps out Node's global fetch dispatcher, which stops NODE_USE_ENV_PROXY from applying.
const { JSDOM } = await import('jsdom')
const doc = new JSDOM(parse.text).window.document
const groups = []
let level = ''
for (const el of doc.querySelectorAll('h3, h4, table.wikitable')) {
  if (el.tagName === 'H3') {
    groups.push({ group: dash(el.textContent), hotspots: [] })
    level = ''
  } else if (el.tagName === 'H4') {
    level = dash(el.textContent)
  } else {
    const rows = [...el.querySelectorAll('tr')].map(tr => [...tr.children].map(c => c.textContent.replace(/\s+/g, ' ').trim()))
    const [header, ...body] = rows
    // The header's "Artefact" cell spans the icon column too, so its cells sit one to the left of the body's.
    if (header[0] !== 'Artefact' || header[2] !== 'Needed') throw new Error(`Unexpected table header: ${header}`)
    const caption = el.querySelector('caption')?.textContent.trim() ?? ''
    const hotspot = caption.replace(/^Artefacts from /i, '')
    if (!hotspot || !level || groups.length === 0) throw new Error(`Table outside a level range: "${caption}"`)
    // The first cell is the artefact's icon, so name and "Needed" sit at columns 1 and 3.
    const artefacts = body.map(r => {
      const needed = Number(r[3].replace(/,/g, ''))
      if (!r[1] || !Number.isInteger(needed) || needed < 1) throw new Error(`Bad row in "${hotspot}": ${r}`)
      return { key: slug(r[1]), name: r[1], needed }
    })
    groups.at(-1).hotspots.push({ level, hotspot: hotspot[0].toUpperCase() + hotspot.slice(1), artefacts })
  }
}

const all = groups.flatMap(g => g.hotspots.flatMap(h => h.artefacts))
const keys = new Set(all.map(a => a.key))
if (keys.size !== all.length) throw new Error('Artefact names are not unique, so slugs would collide')
if (groups.some(g => g.hotspots.length === 0)) throw new Error('A level group has no hotspots')

const lines = [
  '// Generated by scripts/generate-archaeology-data.mjs — do not edit by hand.',
  '// Source: https://runescape.wiki/w/Archaeology_training (Methods section), the "Needed" column of each',
  `// hotspot's artefact table, fetched ${new Date().toISOString().slice(0, 10)}.`,
  "import type { ArchaeologyGroup } from './archaeology'",
  '',
  'export const ARCHAEOLOGY_GROUPS: ArchaeologyGroup[] = [',
]
for (const g of groups) {
  lines.push('  {', `    group: ${quote(g.group)},`, '    hotspots: [')
  for (const h of g.hotspots) {
    lines.push('      {', `        level: ${quote(h.level)},`, `        hotspot: ${quote(h.hotspot)},`, '        artefacts: [')
    for (const a of h.artefacts) lines.push(`          { key: ${quote(a.key)}, name: ${quote(a.name)}, needed: ${a.needed} },`)
    lines.push('        ],', '      },')
  }
  lines.push('    ],', '  },')
}
lines.push(']', '')
writeFileSync(OUT, lines.join('\n'))

const total = all.reduce((n, a) => n + a.needed, 0)
console.log(`${groups.length} groups, ${groups.reduce((n, g) => n + g.hotspots.length, 0)} hotspots, ${all.length} artefacts, ${total} required`)
